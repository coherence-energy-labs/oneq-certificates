r"""R198 part 18: write a Lean module that makes a model's distance a KERNEL-CHECKED theorem, and check that the
committed modules are still exactly what the certified models give.

    python lean_kernel_proof.py --write     # (re)generate lean/CertR198/CertR198/Kernel/*.lean from the targets
    python lean_kernel_proof.py             # GATE (default): regenerate in memory, refuse any difference

A target is (name, morph2026 code, basis, w). Its model is exported exactly as the morph2026 campaign searched it
(`morph2026.model`, T = 1, not time-ordered); the export's sha256 must equal the campaign record's, and the record's
own minimal witness (weight w + 1) is used. The module holds the model literal, its incidence table, one
`decide +kernel` theorem per anchor (the kernel's reduction cache is per declaration, so memory stays bounded),
their combination by rewriting, `cert2_sound_exec` (lean/CertR198/CertR198/Exec.lean) and the witness. Each module
imports the previous one, so lake builds them one at a time (lake has no jobs flag; four in parallel would hold
~10 GB). What Lean proves is about the model literal; that the literal is the circuit's projected DEM rests on the
exporter and stim (gap G10), and on this gate binding the literal to the campaign's certified model hash.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "lean" / "CertR198" / "CertR198" / "Kernel"
RECORDS = ROOT / "evidence" / "circuit_distance_exact" / "records" / "morph2026_campaign.jsonl"
TARGETS = [("C42aZ1", "c42a", "Z", 5), ("C42aX1", "c42a", "X", 5), ("T30aZ1", "t30a", "Z", 4), ("T30aX1", "t30a", "X", 4)]
sys.path.insert(0, str(HERE))


def module_text(name: str, model_path: pathlib.Path, w: int, wit: list[int], after: str | None) -> str:
    lines = model_path.read_text().splitlines()
    nd, nm, no = map(int, lines[0].split()[:3])
    mech = []
    for ln in lines[1:1 + nm]:
        p = list(map(int, ln.split()))
        mech.append((sum(1 << d for d in p[1:1 + p[0]]), p[1 + p[0]]))
    syn = obs = 0
    for i in wit:
        syn ^= mech[i][0]
        obs ^= mech[i][1]
    if syn or not obs or len(set(wit)) != len(wit) or len(wit) != w + 1:
        raise SystemExit(f"REFUSED: {name}'s witness is not an undetectable logical error of weight {w + 1}")
    inc = [[((s, o), i) for i, (s, o) in enumerate(mech) if s >> v & 1] for v in range(nd)]
    sha = hashlib.sha256(model_path.read_bytes()).hexdigest()
    imp = f"CertR198.Kernel.{after}" if after else "CertR198.Exec"
    out = [f"""import {imp}

/-!
# {name}: a circuit distance checked by the Lean kernel

The model is the exported projected detector error model (sha256 `{sha}`):
{nm} mechanisms, {nd} detectors, {no} observables. `cert2` -- whose soundness is `CertR198.Exec.cert2_sound_exec` -- is
evaluated by the kernel one anchor per declaration (`decide +kernel`), so no C code and no compiler is trusted, and
no axiom beyond the standard three is used. Generated by experiments/circuit_distance_exact/lean_kernel_proof.py;
do not edit by hand (its gate refuses any difference).
-/

namespace CertR198.Kernel.{name}

open CertR198 CertR198.Exec
"""]
    out.append(f"/-- {nm} mechanisms `(syndrome mask, observable mask)`, {nd} detectors, {no} observables. -/")
    out.append(f"def model : CModel where\n  nd := {nd}\n  no := {no}\n  mech := [\n    "
               + ",\n    ".join(f"({s}, {o})" for s, o in mech) + "]\n")
    out.append("/-- The incidence table (its completeness is `incOK`, checked below). -/")
    out.append("def tbl : List (List Entry) := [\n  "
               + ",\n  ".join("[" + ", ".join(f"(({s}, {o}), {i})" for (s, o), i in row) + "]" for row in inc) + "]\n")
    out.append(f"theorem len : model.mech.length = {nm} := by decide +kernel\n")
    out.append("theorem tbl_ok : incOK model tbl = true := by decide +kernel\n")
    for i, (s, o) in enumerate(mech):
        out.append(f"theorem anchor{i} : search2 model tbl {i} {s} {o} ({w} - 1) = true := by decide +kernel")
    explicit = "[" + ", ".join(f"(({s}, {o}), {i})" for i, (s, o) in enumerate(mech)) + "]"
    names = ", ".join(f"anchor{i}" for i in range(nm))
    out.append(f"""
set_option maxRecDepth 100000 in
theorem anchors : (model.mech.zipIdx).all (fun p => search2 model tbl p.2 p.1.1 p.1.2 ({w} - 1)) = true := by
  rw [show model.mech.zipIdx = {explicit} from by decide +kernel]
  simp only [List.all_cons, List.all_nil, {names}, Bool.and_true]

theorem cert2_ok : cert2 model tbl {w} = true := by
  simp only [cert2, tbl_ok, anchors, Bool.and_self]

/-- **No undetectable logical error of weight `≤ {w}`** in the model (kernel-checked). -/
theorem no_logical_le_{w} : ∀ X : Finset (Fin model.mech.length), model.toDEM.IsSol X → {w} < X.card :=
  cert2_sound_exec model (by rw [len]; decide) tbl {w} cert2_ok

/-- The witness: {w + 1} mechanisms whose syndromes cancel and whose observables do not. -/
def witness : Finset (Fin model.mech.length) :=
  {{{", ".join(f"⟨{i}, by rw [len]; decide⟩" for i in wit)}}}

set_option maxRecDepth 100000 in
theorem witness_card : witness.card = {w + 1} := by decide +kernel

set_option maxRecDepth 100000 in
theorem witness_sol : model.toDEM.IsSol witness := by
  unfold DEM.IsSol DEM.synSum DEM.obsSum
  decide +kernel

/-- **The model's distance is exactly {w + 1}** (kernel-checked). -/
theorem distance : (∀ X : Finset (Fin model.mech.length), model.toDEM.IsSol X → {w} < X.card) ∧
    model.toDEM.IsSol witness ∧ witness.card = {w + 1} :=
  ⟨no_logical_le_{w}, witness_sol, witness_card⟩

end CertR198.Kernel.{name}
""")
    return "\n".join(out)


def generate(work: pathlib.Path) -> dict[str, str]:
    """name -> module text, from fresh exports bound to the campaign record (SystemExit on any mismatch)."""
    import morph2026 as M
    recs = [json.loads(x) for x in RECORDS.read_text().splitlines() if x.strip()]
    out, after = {}, None
    for name, code, basis, w in TARGETS:
        _, path, _ = M.model(M.spec(code), basis, 1, work, False)
        rec = next(r for r in recs if r["kind"] == "search" and r["code"] == code and r["basis"] == basis
                   and r["rounds"] == 1)
        sha = hashlib.sha256(path.read_bytes()).hexdigest()
        if sha != rec["model_sha256"] or rec["found_weight"] != w + 1 or not rec.get("every_deletion_fails"):
            raise SystemExit(f"REFUSED: {name}: the export is not the campaign's certified model, or its witness is not "
                             f"a minimal weight-{w + 1} one")
        out[name] = module_text(name, path, w, sorted(rec["witness"]), after)
        after = name
    return out


def check() -> list[str]:
    with tempfile.TemporaryDirectory() as d:
        want = generate(pathlib.Path(d))
    bad = []
    for name, text in want.items():
        p = OUT / f"{name}.lean"
        have = p.read_bytes().replace(b"\r\n", b"\n").decode("utf-8") if p.exists() else None
        if have != text:
            bad.append(f"{p.name} differs from what the certified model gives (regenerate with --write)")
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    if a.write:
        OUT.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory() as d:
            for name, text in generate(pathlib.Path(d)).items():
                (OUT / f"{name}.lean").write_bytes(text.encode("utf-8"))
                print("wrote", name)
        return
    bad = check()
    for b in bad:
        print("REFUSED:", b)
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()

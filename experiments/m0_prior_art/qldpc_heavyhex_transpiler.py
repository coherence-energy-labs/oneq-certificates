r"""A5 -- COMPILING [[144,12,12]] ONTO HEAVY-HEX, AND CERTIFYING THE RESULT.

THE SPEC (FTQC_BUILD_PROGRAM A5): code spec x hardware graph -> embedding
minimising SWAP overhead + synthesised syndrome-extraction circuits +
CERTIFICATION THAT THE RESULT IMPLEMENTS THE CODE. Gate: compile
[[144,12,12]] onto heavy-hex (which "shouldn't fit") and publish the
overhead ratio; <3x is immediately adoptable.

WHY IT "SHOULDN'T FIT". A bivariate-bicycle code needs weight-6 checks
whose supports are spread by the cyclic shifts x^3+y+y^2 and y^3+x+x^2 --
long-range in any planar layout. Heavy-hex is degree <= 3 and planar. So
every check has to be routed, and the interesting question is not whether
it fits (a connected graph can route anything) but WHAT IT COSTS.

THE THREE PARTS, and which one is ours.

  EMBEDDING is a placement problem: put 144 data + 144 ancilla qubits on
  lattice sites minimising total routing distance. Annealed here.

  ROUTING is a Steiner tree problem: connect each ancilla to its 6 data
  qubits through a degree-3 lattice. Shortest-path heuristic, then the
  CNOT sequence is a fan-in along the tree and its exact reverse, so the
  routing qubits are returned to |0> and the block is a clean stabilizer
  measurement. Cost 2|E| CNOTs for a tree with |E| edges, against 6 with
  native connectivity.

  CERTIFICATION is the part this program exists for, and the part the
  literature's overhead numbers do not carry. A compiled circuit that is
  ROUTED CORRECTLY and a compiled circuit that MEASURES THE INTENDED
  STABILIZER are different claims, and an off-by-one in a Steiner tree
  produces a circuit that runs, looks plausible, and measures the wrong
  operator. So every synthesised block is verified by SYMPLECTIC
  PROPAGATION: push the ancilla's Z through the CNOT list and require the
  resulting operator's support to equal the intended check support
  EXACTLY -- not a subset, not a superset. A routing qubit left entangled
  fails the same test, because it shows up in the propagated support.

WHAT IS PUBLISHED. The overhead ratio against the native cost, which for
144 weight-6 checks is 864 CNOTs per syndrome cycle -- the count the
Bravyi et al. schedule achieves with the code's own connectivity. Plus a
greedily-scheduled depth, labelled greedy because it is an upper bound
from one heuristic and not a claimed optimum.

HONEST SCOPE, AND IT CUTS BOTH WAYS. The lattice is an IBM-STYLE
heavy-hex model generated by the function below (degree <= 3, verified),
not a specific device's coupling map with its calibration-dependent dead
edges.

  OPTIMISTIC: the cost model counts two-qubit gates only -- no crosstalk,
  no leakage, no control-stack scheduling constraints. Each of those
  makes a real device worse.

  PESSIMISTIC: the router is a nearest-neighbour ancilla walk with an
  exact retrace, not a state-of-the-art SWAP-network synthesiser, and the
  placement is annealed rather than solved. A better compiler will beat
  this number.

So this is an UPPER BOUND FROM THIS COMPILER under an idealised gate
count. It is emphatically NOT a proof that no better compilation exists,
and the write-up must not be read as one. What it IS: a certified,
reproducible number where the literature currently has none, with the
retrace-free bound reported alongside so the reader can see how much of
the cost is the router's conservatism rather than the code's geometry.
"""


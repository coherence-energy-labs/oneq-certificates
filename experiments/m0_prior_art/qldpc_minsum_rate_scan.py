r"""Every BP-OSD arm of paper 2, at every noise level, across declared error rates that exact arithmetic cannot tell apart.

    python experiments/m0_prior_art/qldpc_minsum_rate_scan.py [--workers 4]

WHY (paper 2, third referee, 2026-11-02, finding M1). qldpc_minsum_rate_invariance.py established that min-sum BP-OSD
with a uniform prior is invariant to the declared rate in exact arithmetic, and that at scaling factor 1 the answers
nonetheless change with it (floating-point ties). Then an unscaled arm reported AT ONE DECLARED RATE is not a property
of the decoder: configuration B told 0.05 or 0.07 is the same decoder in exact arithmetic, yet on the p = 0.05
syndromes it finds the optimum on 87 or 196 of 200. Every comparison the paper draws from an unscaled arm must hold
across the rates, or it is a rounding artifact. This measures, for each arm and dataset, at each of the 16 declared
rates of qldpc_bposd_scaling_sensitivity.py:
  * optimum hits (syndrome-valid with the certified optimum's weight -- uniform weights, so the reference's length),
  * logical failures against the sampled error (simulation truth),
  * BP convergence, shots with an exact-zero soft value, and failures on shots where BP converged,
  * how many shots keep ONE answer across all 16 rates.
Arms: A (30 iterations, OSD-CS 5) and B (100, OSD-CS 10) of qldpc_strong_baseline_gate at scaling 1; the same at 0.625
(A_s, B_s); and the same at scaling 1 with a fixed relative 1e-6 jitter of the prior LLRs (A_j, B_j), which breaks
exact ties and keeps the exact-arithmetic invariance. Datasets: the strong-baseline v3 syndromes at p = 0.01 ... 0.07,
and the held-out stress rung's 300 syndromes (faults regenerated by the campaign's seed rule, which must reproduce
every stored syndrome). The as-run value of each arm is the one at declared rate = the dataset's p.
Post hoc; nothing here was preregistered.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import pathlib
import sys
from concurrent.futures import ProcessPoolExecutor

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments" / "m0_prior_art"))
OUT = ROOT / "evidence" / "qldpc_minsum_rate_scan.json"
V3 = ROOT / "evidence" / "strong_baseline_v3"
SENS = ROOT / "evidence" / "qldpc_bposd_scaling_sensitivity.json"
LEVELS = ["0.01", "0.02", "0.03", "0.05", "0.07"]
ARMS = {"A": ("baseline_30_osdcs5", 1.0, False), "B": ("strong_100_osdcs10", 1.0, False),
        "A_s": ("baseline_30_osdcs5", 0.625, False), "B_s": ("strong_100_osdcs10", 0.625, False),
        "A_j": ("baseline_30_osdcs5", 1.0, True), "B_j": ("strong_100_osdcs10", 1.0, True)}
JITTER_SEED = 20261102                       # the same fixed jitter as qldpc_minsum_rate_invariance.py


def _dataset(name: str):
    """(syndromes, true errors, certified optimum weights, declared-as-run rate) for one dataset."""
    from qldpc_bb_gate import bb_gross_code
    _, HZ = bb_gross_code()
    n = HZ.shape[1]
    if name.startswith("strong p="):
        lv = name.split("=")[1]
        shots = [json.loads(x) for x in (V3 / f"p{lv}_shots.jsonl").read_text(encoding="utf-8").splitlines()
                 if x.strip()]
        syn = [s["syndrome_support"] for s in shots]
        err = [s["true_error_support"] for s in shots]
        U = [len(s["reference"]["support"]) for s in shots]
        return syn, err, U, float(lv)
    # the held-out stress rung: regenerate the faults exactly as qldpc_heldout_scaled_posthoc.py does
    from qldpc_heldout_gate import heldout_seed
    recs = [json.loads(x) for x in (ROOT / "evidence" / "per_shot" / "heldout_stress_p05.jsonl")
            .read_text(encoding="utf-8").splitlines() if x.strip()]
    freeze = json.loads((ROOT / "evidence" / "qldpc_heldout.json").read_text(encoding="utf-8"))["freeze_commit"]
    rng = np.random.default_rng(heldout_seed("stress_p05", freeze))
    faults = []
    while len(faults) < len(recs):
        e = (rng.random(n) < np.full(n, 0.05)).astype(np.uint8)
        if ((HZ @ e) % 2).any():
            faults.append(e)
    syn, err = [], []
    for r, e in zip(recs, faults):
        s = sorted(int(j) for j in np.flatnonzero((HZ @ e) % 2))
        if s != sorted(r["instance"]["syndrome_support"]):
            raise SystemExit("held-out stress: the seed rule no longer regenerates the stored syndromes")
        syn.append(s)
        err.append([int(i) for i in np.flatnonzero(e)])
    return syn, err, [len(r["receipt"]["answer"]) for r in recs], 0.05


def _run(job: tuple) -> dict:
    dataset, arm, rate = job
    from ldpc import BpOsdDecoder
    from scipy.sparse import csr_matrix
    from qldpc_bb_gate import bb_gross_code, gf2_in_rowspace, gf2_row_reduce
    from qldpc_strong_baseline_gate import CONFIGS
    HX, HZ = bb_gross_code()
    n = HZ.shape[1]
    xb, xp = gf2_row_reduce(HX % 2)
    syns, errs, Us, _ = _dataset(dataset)
    label, alpha, jit = ARMS[arm]
    if jit:
        L = math.log((1 - rate) / rate) * (1.0 + 1e-6 * np.random.default_rng(JITTER_SEED).random(n))
        dec = BpOsdDecoder(csr_matrix(HZ), error_channel=list(1.0 / (1.0 + np.exp(L))), ms_scaling_factor=alpha,
                           **CONFIGS[label])
    else:
        dec = BpOsdDecoder(csr_matrix(HZ), error_rate=rate, ms_scaling_factor=alpha, **CONFIGS[label])
    out = dict(hits=0, failures=0, converged=0, zero_soft_shots=0, failures_converged=0, answers=[])
    for sup, tru, U in zip(syns, errs, Us):
        s = np.zeros(HZ.shape[0], dtype=np.uint8)
        s[sup] = 1
        e = np.asarray(dec.decode(s)).astype(np.uint8)
        valid = bool(np.array_equal((HZ @ e) % 2, s))
        t = np.zeros(n, dtype=np.uint8)
        t[tru] = 1
        f = (e ^ t) % 2
        fail = bool(((HZ @ f) % 2).any()) or not gf2_in_rowspace(xb, xp, f, n)
        conv = bool(dec.converge)
        out["hits"] += valid and int(e.sum()) == U
        out["failures"] += fail
        out["converged"] += conv
        out["failures_converged"] += fail and conv
        out["zero_soft_shots"] += bool((np.asarray(dec.log_prob_ratios, dtype=float) == 0).any())
        out["answers"].append(hashlib.sha256(np.flatnonzero(e).astype(np.int32).tobytes()).hexdigest()[:16])
    return {"dataset": dataset, "arm": arm, "rate": rate, **out}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=4)
    a = ap.parse_args()
    import ldpc
    rates = [float(r) for r in json.loads(SENS.read_text(encoding="utf-8"))["declared_rate_scan"]
             ["p=0.05 strong_100_osdcs10"]]
    datasets = [f"strong p={lv}" for lv in LEVELS] + ["heldout stress_p05"]
    jobs = [(d, arm, r) for d in datasets for arm in ARMS for r in rates]
    with ProcessPoolExecutor(a.workers) as ex:
        res = list(ex.map(_run, jobs, chunksize=4))
    out = {"schema": "oneq-qldpc-minsum-rate-scan/1", "ldpc": ldpc.__version__, "post_hoc": "not preregistered",
           "rates": rates, "arms": {k: {"config": v[0], "ms_scaling_factor": v[1], "jitter_1e-6": v[2]}
                                    for k, v in ARMS.items()}, "datasets": {}}
    for d in datasets:
        as_run = _dataset(d)[3]
        out["datasets"][d] = {"as_run_rate": as_run, "shots": len(_dataset(d)[0]), "arms": {}}
        for arm in ARMS:
            rows = {r["rate"]: r for r in res if r["dataset"] == d and r["arm"] == arm}
            per = {str(rt): {k: rows[rt][k] for k in ("hits", "failures", "converged", "zero_soft_shots",
                                                     "failures_converged")} for rt in rates}
            nsh = len(rows[rates[0]]["answers"])
            one = sum(len({rows[rt]["answers"][i] for rt in rates}) == 1 for i in range(nsh))
            col = lambda k: [per[str(rt)][k] for rt in rates]  # noqa: E731
            out["datasets"][d]["arms"][arm] = {
                "as_run": per[str(as_run)], "per_rate": per, "shots_with_one_answer": one,
                **{f"{k}_min": min(col(k)) for k in ("hits", "failures", "converged")},
                **{f"{k}_max": max(col(k)) for k in ("hits", "failures", "converged")}}
            v = out["datasets"][d]["arms"][arm]
            print(f"{d:20s} {arm:4s} hits {v['hits_min']:3d}-{v['hits_max']:3d} (as run {v['as_run']['hits']:3d})  "
                  f"failures {v['failures_min']:3d}-{v['failures_max']:3d}  converged {v['converged_min']}-"
                  f"{v['converged_max']}  one-answer {one}/{nsh}", flush=True)
    OUT.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
